// --- BUILT-IN GRAPHICS ENGINE ---
function rgba(r: u32, g: u32, b: u32, a: u32 = 255): u32 {
  return (a << 24) | (b << 16) | (g << 8) | r;
}

function setPixel(x: i32, y: i32, color: u32): void {
  if (x >= 0 && x < WIDTH && y >= 0 && y < HEIGHT) pixels[y * WIDTH + x] = color;
}

function drawRect(x: i32, y: i32, w: i32, h: i32, color: u32): void {
  for (let iy = y; iy < y + h; iy++) {
    for (let ix = x; ix < x + w; ix++) setPixel(ix, iy, color);
  }
}

function drawFrame(x: i32, y: i32, w: i32, h: i32, color: u32): void {
  for (let ix = x; ix < x + w; ix++) { setPixel(ix, y, color); setPixel(ix, y + h - 1, color); }
  for (let iy = y; iy < y + h; iy++) { setPixel(x, iy, color); setPixel(x + w - 1, iy, color); }
}

function drawChar(c: i32, x: i32, y: i32, color: u32, scale: i32 = 1): void {
  if (c < 32 || c > 126) return;
  let idx = (c - 32) * 8;
  if (idx + 7 >= FONT.length) return;
  for (let ly: i32 = 0; ly < 8; ly++) {
    let line: u32 = <u32>unchecked(FONT[idx + ly]);
    for (let lx: i32 = 0; lx < 8; lx++) {
      if (((line >> <u32>(7 - lx)) & 1) != 0) {
        if (scale == 1) {
          setPixel(x + lx, y + ly, color);
        } else {
          drawRect(x + lx * scale, y + ly * scale, scale, scale, color);
        }
      }
    }
  }
}

function drawText(txt: string, x: i32, y: i32, color: u32, scale: i32 = 1): void {
  let currX = x;
  for (let i = 0; i < txt.length; i++) {
    drawChar(txt.charCodeAt(i), currX, y, color, scale);
    currX += 8 * scale;
  }
}

