class RtspSession {
  wsId: i32 = -1;
  cseq: i32 = 1;
  url: string = "";
  isConnected: bool = false;

  connect(wsProxyUrl: string, rtspStreamUrl: string): void {
    this.url = rtspStreamUrl;
    let b = String.UTF8.encode(wsProxyUrl);
    this.wsId = host_ws_connect(changetype<usize>(b), b.byteLength);
  }

  sendDescribe(): void {
    let req = "DESCRIBE " + this.url + " RTSP/1.0\r\nCSeq: " + (this.cseq++).toString() + "\r\nAccept: application/sdp\r\n\r\n";
    this.send(req);
  }

  sendSetup(track: string = "trackID=0"): void {
    let req = "SETUP " + this.url + "/" + track + " RTSP/1.0\r\nCSeq: " + (this.cseq++).toString() + "\r\nTransport: RTP/AVP/TCP;unicast;interleaved=0-1\r\n\r\n";
    this.send(req);
  }

  sendPlay(): void {
    let req = "PLAY " + this.url + " RTSP/1.0\r\nCSeq: " + (this.cseq++).toString() + "\r\nRange: npt=0.000-\r\n\r\n";
    this.send(req);
  }

  private send(str: string): void {
    if (this.wsId == -1) return;
    let b = String.UTF8.encode(str);
    host_ws_send(this.wsId, changetype<usize>(b), b.byteLength);
  }
}

// Generic raw TCP convenience wrapper. Protocol framing stays in the WASM app.
// tcp_state: 0=connecting, 1=open, 2=closing, 3=closed, -1=error.
// flags: bit 0=keep-alive, bit 1=no-delay.
class RawTcpSocket {
  id: i32 = -1;

  static capabilities(): i32 {
    return host_socket_capabilities();
  }

  connect(host: string, port: i32, flags: i32 = 3): i32 {
    let h = String.UTF8.encode(host);
    this.id = host_tcp_connect(changetype<usize>(h), h.byteLength, port, flags);
    return this.id;
  }

  state(): i32 {
    return this.id >= 0 ? host_tcp_state(this.id) : -1;
  }

  sendBytes(data: Uint8Array): i32 {
    if (this.id < 0) return -1;
    return host_tcp_send(this.id, changetype<usize>(data.dataStart), data.byteLength);
  }

  sendText(text: string): i32 {
    if (this.id < 0) return -1;
    let data = String.UTF8.encode(text);
    return host_tcp_send(this.id, changetype<usize>(data), data.byteLength);
  }

  receive(out: Uint8Array): i32 {
    if (this.id < 0) return -1;
    return host_tcp_receive(this.id, changetype<usize>(out.dataStart), out.byteLength);
  }

  pending(): i32 {
    return this.id >= 0 ? host_tcp_pending(this.id) : 0;
  }

  error(): string {
    if (this.id < 0) return "socket is not connected";
    let size = host_tcp_error_size(this.id);
    if (size <= 0) return "";
    let data = new ArrayBuffer(size);
    let read = host_tcp_read_error(this.id, changetype<usize>(data), size);
    return read > 0 ? String.UTF8.decode(data) : "";
  }

  close(): i32 {
    if (this.id < 0) return 0;
    let result = host_tcp_close(this.id);
    this.id = -1;
    return result;
  }
}

// --- BUILT-IN HTTP CLIENT ---
class HttpResponse {
  status: i32 = 0;
  body: string = "";
}

class HttpClient {
  static get(url: string): i32 {
    let uBuf = String.UTF8.encode(url);
    let mBuf = String.UTF8.encode("GET");
    return host_http_request(changetype<usize>(mBuf), mBuf.byteLength, changetype<usize>(uBuf), uBuf.byteLength, 0, 0);
  }
  static post(url: string, payload: string): i32 {
    let uBuf = String.UTF8.encode(url);
    let pBuf = String.UTF8.encode(payload);
    let mBuf = String.UTF8.encode("POST");
    return host_http_request(changetype<usize>(mBuf), mBuf.byteLength, changetype<usize>(uBuf), uBuf.byteLength, changetype<usize>(pBuf), pBuf.byteLength);
  }
  static poll(reqId: i32): HttpResponse | null {
    let status = host_http_get_status(reqId);
    if (status == 0) return null;
    let size = host_http_get_response_size(reqId);
    let res = new HttpResponse();
    res.status = status;
    if (size > 0) {
      let buf = new ArrayBuffer(size);
      host_http_read_response(reqId, changetype<usize>(buf), size);
      res.body = String.UTF8.decode(buf);
    }
    return res;
  }
}
